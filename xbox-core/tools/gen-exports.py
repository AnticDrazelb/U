#!/usr/bin/env python3
"""Generates src/exports.inc from nxdk's lib/xboxkrnl/xboxkrnl.exe.def (CC0-1.0, 2017 Stefan
Schmidt): every xboxkrnl.exe export with its ordinal, calling convention and argument bytes.

    gen-exports.py <nxdk>/lib/xboxkrnl/xboxkrnl.exe.def > src/exports.inc
"""
import re
import sys

print("// Generated by tools/gen-exports.py from nxdk's xboxkrnl.exe.def (CC0-1.0). Do not edit.")
print("// X(ordinal, name, kind, argument bytes): kind S = stdcall, F = fastcall, D = data")
for line in open(sys.argv[1]):
    m = re.match(r"\s*(@?)([A-Za-z_][A-Za-z0-9_]*)(?:@(\d+))?\s+@\s*(\d+)\s+NONAME(\s+DATA)?", line)
    if not m:
        continue
    fast, name, args, ordinal, data = m.groups()
    kind = "D" if data else "F" if fast else "S"
    print(f"X({ordinal}, {name}, {kind}, {args or 0})")
